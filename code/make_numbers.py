"""
make_numbers.py — generate numbers.tex from the result files.

Every quantity quoted in the manuscript text is defined here as a LaTeX macro
computed from results_v2/*.csv.  The manuscript never hard-codes a number, so
text and results cannot drift apart (this is what went wrong in the previous
version, where the abstract said "tie" while the table said otherwise).
"""
import os
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CV_FILE = os.environ.get("CV_FILE", "cv_metrics.csv")
RES = os.path.join(ROOT, "results_v2")
OUT = os.path.join(ROOT, "resubmission", "manuscript", "numbers.tex")

LEARNED = "istanet"


def f(x, d=2):
    return f"{x:.{d}f}"


def main():
    cv = pd.read_csv(os.path.join(RES, CV_FILE))
    # Seed 0 only would contradict the main table, which is seed-averaged: the
    # learned decoders are trained with three seeds and the per-recording value
    # is their mean. Averaging here keeps text and table identical by
    # construction.
    cv = cv[(cv.phi == "gaussian") & (cv.bits == "none")]
    per_rec = (cv.groupby(["cr", "method", "record"])
                 .agg(PRDN=("PRDN", "mean"), SNR=("SNR", "mean")).reset_index())
    summ = per_rec.groupby(["cr", "method"]).agg(
        PRDN=("PRDN", "mean"), SNR=("SNR", "mean"), sd=("PRDN", "std"),
        n=("record", "nunique")).reset_index()

    L = []
    L.append("% auto-generated by code_v2/make_numbers.py -- do not edit")
    L.append(f"\\newcommand{{\\NRECORDS}}{{{int(per_rec.record.nunique())}}}")
    L.append(f"\\newcommand{{\\NFOLDS}}{{{int(cv.fold.nunique())}}}")
    L.append(f"\\newcommand{{\\NWINTOT}}{{{int(cv.n_win.sum()):,}}}".replace(",", "\\,"))

    tag = {0.25: "A", 0.5: "B", 0.75: "C"}
    for cr, t in tag.items():
        sub = summ[summ.cr == cr].set_index("method")
        if sub.empty:
            continue
        for meth, mname in [("fista", "Fista"), ("omp", "Omp"), ("bsbl", "Bsbl"),
                            ("ksvd_omp", "Ksvd"), ("istanet", "Net"),
                            ("hua", "Hua"), ("hua_learned", "HuaL"),
                            ("dilated", "Dil"), ("ista", "Ista")]:
            if meth in sub.index:
                L.append(f"\\newcommand{{\\prd{mname}{t}}}{{{f(sub.loc[meth,'PRDN'])}}}")
                L.append(f"\\newcommand{{\\snr{mname}{t}}}{{{f(sub.loc[meth,'SNR'])}}}")
        # best classical (non-learned) method at this CR
        classical = [m for m in ("ista", "fista", "omp", "ksvd_omp", "bsbl")
                     if m in sub.index]
        if classical and LEARNED in sub.index:
            bestc = sub.loc[classical, "PRDN"].idxmin()
            L.append(f"\\newcommand{{\\bestclass{t}}}{{{bestc}}}")
            L.append(f"\\newcommand{{\\prdbestclass{t}}}{{{f(sub.loc[bestc,'PRDN'])}}}")
            ratio = sub.loc[bestc, "PRDN"] / sub.loc[LEARNED, "PRDN"]
            L.append(f"\\newcommand{{\\gain{t}}}{{{f(ratio, 2)}}}")

    # significance vs the learned decoder
    sig_p = os.path.join(RES, "significance.csv")
    if os.path.exists(sig_p):
        sig = pd.read_csv(sig_p)
        for cr, t in tag.items():
            s = sig[(sig.cr == cr)]
            for meth, mname in [("bsbl", "Bsbl"), ("ksvd_omp", "Ksvd"),
                                ("fista", "Fista"), ("omp", "Omp")]:
                r = s[s.method == meth]
                if len(r):
                    p = float(r.p_holm.iloc[0])
                    L.append(f"\\newcommand{{\\p{mname}{t}}}{{"
                             f"{'<0.001' if p < 1e-3 else f(p,3)}}}")

    # ---- paired comparison vs BSBL at CR 0.75 + seed spreads ----
    if os.path.exists(sig_p):
        sg = pd.read_csv(sig_p)
        r = sg[(sg.cr == 0.75) & (sg.method == "bsbl")]
        if len(r):
            r = r.iloc[0]
            L.append(f"\\newcommand{{\\dNetBsblC}}{{{r.median_diff_PRDN:+.2f}}}")
            L.append(f"\\newcommand{{\\ciNetBsblC}}{{[{r.ci_lo:+.2f},\\,{r.ci_hi:+.2f}]}}")
            L.append(f"\\newcommand{{\\pNetBsblC}}{{{r.p_holm:.3f}}}")
    # seed spread needs the unfiltered table: `cv` above is seed 0 only
    _all = pd.read_csv(os.path.join(RES, CV_FILE))
    _all = _all[(_all.phi == "gaussian")]
    _sd = _all[_all.method.isin(["istanet", "hua", "dilated"])]
    if _sd.seed.nunique() > 1:
        sp = _sd.groupby(["cr", "method", "seed"]).PRDN.mean().groupby(level=[0, 1]).std()
        if (0.75, "istanet") in sp.index:
            L.append(f"\\newcommand{{\\sdNetC}}{{{sp.loc[(0.75,'istanet')]:.2f}}}")
        pub = [sp.loc[(0.75, m)] for m in ("hua", "dilated") if (0.75, m) in sp.index]
        if pub:
            L.append(f"\\newcommand{{\\sdPubC}}{{{max(pub):.2f}}}")

    # quantisation / energy
    qe_p = os.path.join(RES, "quant_energy.csv")
    if os.path.exists(qe_p):
        qe = pd.read_csv(qe_p)
        g = qe[(qe.cr == 0.75) & (qe.method == "istanet")]
        if len(g):
            dense = g[(g.phi == "gaussian") & (g.bits.isna())]
            sb8 = g[(g.phi == "sparse_binary") & (g.bits == 8)]
            if len(dense) and len(sb8):
                L.append(f"\\newcommand{{\\prdDenseFloat}}{{{f(dense.PRDN.iloc[0])}}}")
                L.append(f"\\newcommand{{\\prdSparseEight}}{{{f(sb8.PRDN.iloc[0])}}}")
                L.append(f"\\newcommand{{\\rateDenseFloat}}{{{dense.bit_rate_bps.iloc[0]:.0f}}}")
                L.append(f"\\newcommand{{\\rateSparseEight}}{{{sb8.bit_rate_bps.iloc[0]:.0f}}}")
                L.append(f"\\newcommand{{\\rateDrop}}{{"
                         f"{f(dense.bit_rate_bps.iloc[0]/sb8.bit_rate_bps.iloc[0],1)}}}")

    # complexity
    cx_p = os.path.join(RES, "complexity.csv")
    if os.path.exists(cx_p):
        cx = pd.read_csv(cx_p)
        r = cx[(cx.cr == 0.75) & (cx.method == "istanet")]
        if len(r):
            L.append(f"\\newcommand{{\\netParams}}{{{int(r.params.iloc[0]):,}}}".replace(",", "\\,"))
            L.append(f"\\newcommand{{\\netMacs}}{{{r.macs_per_window.iloc[0]/1e6:.1f}}}")
            L.append(f"\\newcommand{{\\netMs}}{{{r.infer_ms_per_window.iloc[0]:.3f}}}")

    # cross-database
    cd_p = os.path.join(RES, "crossdb.csv")
    if os.path.exists(cd_p):
        cd = pd.read_csv(cd_p)
        for cr, t in tag.items():
            for db in ("mitbih", "ptb"):
                for meth, mname in [("istanet", "Net"), ("bsbl", "Bsbl"),
                                    ("fista", "Fista")]:
                    v = cd[(cd.cr == cr) & (cd.test_db == db) & (cd.method == meth)]
                    if len(v):
                        L.append(f"\\newcommand{{\\x{mname}{db.capitalize()}{t}}}"
                                 f"{{{f(v.PRDN.mean())}}}")

    # ablation
    ab_p = os.path.join(RES, "ablation.csv")
    if os.path.exists(ab_p):
        ab = pd.read_csv(ab_p)
        a = ab[(ab.cr == 0.75) & (ab.variant == "stages")]
        if len(a):
            L.append(f"\\newcommand{{\\ablStageOne}}{{{f(a[a.stages==1].PRDN.mean())}}}")
            L.append(f"\\newcommand{{\\ablStageEight}}{{{f(a[a.stages==8].PRDN.mean())}}}")
        for var, nm in (("no_learned_prox", "NoProx"), ("fixed_threshold", "FixThr")):
            v = ab[(ab.cr == 0.75) & (ab.variant == var)]
            if len(v):
                L.append(f"\\newcommand{{\\abl{nm}}}{{{f(v.PRDN.mean())}}}")


    # ---- clinical endpoints ----
    q_p = os.path.join(RES, "cv3_qrs.csv")
    if os.path.exists(q_p):
        q = pd.read_csv(q_p).drop_duplicates(
            subset=["fold", "cr", "seed", "method", "record"], keep="last")
        L.append(f"\\newcommand{{\\QRSWORST}}{{{max(q.f1_drop.max(), 0):.3f}}}")
        L.append(f"\\newcommand{{\\NBEATS}}{{{int(q.groupby('record').n_beats.first().sum()):,}}}".replace(",", "\\,"))
    m_p = os.path.join(RES, "morph.csv")
    if os.path.exists(m_p):
        mo = pd.read_csv(m_p)
        g = mo.groupby(["cr", "method"]).st_frac_gt_0p1.mean() * 100
        for meth, nm in (("ista", "Ista"), ("istanet", "Net"), ("dilated", "Dil"),
                         ("bsbl", "Bsbl"), ("hua", "Hua")):
            for cr, t in ((0.25, "A"), (0.5, "B"), (0.75, "C")):
                if (cr, meth) in g.index:
                    L.append(f"\\newcommand{{\\st{nm}{t}}}{{{g.loc[(cr, meth)]:.0f}}}")
        a = mo[mo.cr == 0.25].groupby("method").st_frac_gt_0p1.mean().max() * 100
        L.append(f"\\newcommand{{\\stWorstA}}{{{a:.0f}}}")
        # beats actually used for the morphology endpoint
        uniq = int(mo.groupby("record").n_beats.first().sum())
        L.append(f"\\newcommand{{\\NBEATSMORPH}}{{{uniq:,}}}".replace(",", "\\,"))
        L.append(f"\\newcommand{{\\NMEASMORPH}}{{{int(mo.n_beats.sum()):,}}}".replace(",", "\\,"))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L)} macros)")
    for l in L[:12]:
        print("   ", l)


if __name__ == "__main__":
    main()
